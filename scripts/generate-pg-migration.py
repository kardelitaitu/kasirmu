#!/usr/bin/env python3
"""Generate the Postgres port of the FULLY-MIGRATED SQLite schema.

Pipeline (rebuilt 2026-08-31; the old text-based version read only the
frozen 20260813_init.sql and silently diverged from the 14+ incremental
migrations — the drift the loyalty work exposed):

1. Parse the migration registry order from crates/oz-core/src/migrations.rs
   (the canonical source — registry order is NOT plain filename order).
2. Apply every migration to an in-memory SQLite database (python sqlite3,
   needs SQLite >= 3.35 for ALTER TABLE ... DROP COLUMN).
3. Dump the FINAL state: CREATE TABLE / index / trigger text from
   sqlite_master (SQLite keeps it current across ADD/DROP COLUMN), plus
   seed rows from every table that ends up non-empty.
4. Translate to Postgres DDL:

   * ``strftime('%Y-%m-%dT%H:%M:%fZ', 'now')`` → ISO-8601 ``to_char(now() …)``
   * ``datetime('now')`` → ``to_char(now() …)``
   * ``INTEGER`` → ``BIGINT`` (SQLite INTEGER is 64-bit, like Rust ``i64``)
   * ``REAL`` → ``DOUBLE PRECISION``
   * ``INTEGER PRIMARY KEY AUTOINCREMENT`` → ``BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY``
   * ``) STRICT`` table option → dropped (Postgres has no equivalent)
   * seeds → ``INSERT … ON CONFLICT DO NOTHING`` (idempotent re-apply);
     timestamp values that are "now"-derived (column DEFAULT or an
     explicit strftime in the seed INSERT — detected by freshness, see
     _quote) are re-emitted as the PG now-expression so output stays
     deterministic
   * triggers → hand-written plpgsql from TRIGGER_MAP; every dumped
     trigger needs an entry and every entry must be live (fail closed
     both ways — the ERR-10 stale-exemption discipline)
   * RLS appendix → curated RLS_TABLES list (enabling RLS is a policy
     decision: the write path must populate tenant_id); the generator
     fails if an entry loses its table or column, and lists tenant_id
     tables not yet covered as a visible comment — every uncovered
     table must carry a documented reason in RLS_EXEMPT or generation
     fails (coverage debt can neither appear nor vanish silently)

5. Re-emit CREATE TABLE in **topological order** (Kahn over
   ``REFERENCES t(col)``): SQLite tolerates forward FK references,
   Postgres does not.

Usage:

    python3 scripts/generate-pg-migration.py           # write the file
    python3 scripts/generate-pg-migration.py --check   # drift guard, writes nothing

--check renders the output twice (two independent migration runs) and
fails on any difference — that is the determinism self-proof — then
compares against the committed file (newline-normalized) and exits 1 on
drift without touching the working tree. CI runs --check; the pre-commit
hook runs it whenever a migration file or this script is staged.
"""

