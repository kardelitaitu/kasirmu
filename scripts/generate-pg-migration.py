def _chunks(items: list[str], size: int):
    for i in range(0, len(items), size):
        yield items[i : i + size]


RLS_TEMPLATE = """-- ── Row-Level Security: tenant isolation (PG-only) ─────────────────────
-- Curated coverage list (RLS_TABLES in scripts/generate-pg-migration.py);
-- the generator fails if an entry loses its tenant_id column or table.
DO $$
DECLARE
    t text;
BEGIN
    FOREACH t IN ARRAY ARRAY[__TABLES__]
    LOOP
        EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        IF NOT EXISTS (
            SELECT 1 FROM pg_policies
            WHERE schemaname = 'public' AND tablename = t AND policyname = 'tenant_isolation'
        ) THEN
            EXECUTE format(
                'CREATE POLICY tenant_isolation ON %I
                 USING (tenant_id = current_setting(''oz.tenant_id'', true))
                 WITH CHECK (tenant_id = current_setting(''oz.tenant_id'', true))',
                t
            );
        END IF;
    END LOOP;
END $$;
"""


def render() -> tuple[str, int, int, int, list[str]]:
    ids = registry_ids()
    db = build_db(ids)

    tables: list[tuple[str, set[str], str]] = []
    for name, sql in db.execute(
        "SELECT name, sql FROM sqlite_master WHERE type='table' "
        "AND name NOT LIKE 'sqlite_%' ORDER BY rowid"
    ):
        refs = set(re.findall(r'REFERENCES\s+"?(\w+)"?\s*\(', sql))
        tables.append((name, refs, convert_table(sql)))
    ordered = topo_sort(tables)

    indexes: list[str] = []
    unique_by_table: dict[str, list[str]] = defaultdict(list)
    skipped: list[str] = []
    for name, tbl, sql in db.execute(
        "SELECT name, tbl_name, sql FROM sqlite_master WHERE type='index' "
        "AND sql IS NOT NULL ORDER BY name"
    ):
        if name in SQLITE_ONLY_INDEXES:
            skipped.append(name)
            continue
        s = re.sub(
            r"^CREATE (UNIQUE )?INDEX (?!IF NOT EXISTS)",
            r"CREATE \1INDEX IF NOT EXISTS ",
            sql,
        )
        s = s.rstrip().rstrip(";") + ";"
        # UNIQUE indexes must exist BEFORE any table whose FK references
        # their columns (composite FKs target them, and PG validates at
        # CREATE TABLE time) — emit each table's unique indexes directly
        # after that table in the topological loop.
        if s.upper().startswith("CREATE UNIQUE INDEX"):
            unique_by_table[tbl].append(s)
        else:
            indexes.append(s)

    dumped_triggers = [
        r[0]
        for r in db.execute(
            "SELECT name FROM sqlite_master WHERE type='trigger' ORDER BY name"
        )
    ]
    missing = [t for t in dumped_triggers if t not in TRIGGER_MAP]
    stale = [t for t in TRIGGER_MAP if t not in dumped_triggers]
    if missing or stale:
        parts = []
        if missing:
            parts.append(f"no plpgsql port: {', '.join(missing)}")
        if stale:
            parts.append(f"stale TRIGGER_MAP entries: {', '.join(stale)}")
        raise SystemExit("error: trigger parity broken — " + "; ".join(parts))

    seeds = dump_seeds(db, [name for name, _, _ in ordered])
    db.close()

    out: list[str] = [HEADER.rstrip(), ""]
    for name, _refs, stmt in ordered:
        out.extend([stmt, ""])
        for idx in unique_by_table.get(name, []):
            out.extend([idx, ""])
    for trig in sorted(TRIGGER_MAP):
        out.extend([TRIGGER_MAP[trig], ""])
    for idx in indexes:
        out.extend([idx, ""])
    for seed in seeds:
        out.extend([seed, ""])
    out.extend([dump_rls(build_db(ids)), ""])

    return "\n".join(out).replace("\n", "\r\n") + "\n", len(ordered), len(indexes), len(seeds), skipped


def main(argv: list[str]) -> int:
    check = "--check" in argv
    if "--self-test" in argv:
        _self_test_rls_gate()
        return 0
    body, n_tables, n_indexes, n_seeds, skipped = render()

    # Determinism self-proof: a second independent migration run must
    # render byte-identical output (this is what makes --check honest).
    body2, *_ = render()
    if body != body2:
        print("error: generator output is not deterministic across runs", file=sys.stderr)
        return 1

    if check:
        committed = DST.read_text(encoding="utf-8").replace("\r\n", "\n")
        if committed == body.replace("\r\n", "\n"):
            print(f"ok: {DST.name} matches the generator ({n_tables} tables, "
                  f"{n_indexes} indexes, {n_seeds} seed inserts)")
            return 0
        gen_lines = body.replace("\r\n", "\n").splitlines()
        com_lines = committed.splitlines()
        diff = sum(1 for a, b in zip(gen_lines, com_lines) if a != b)
        diff += abs(len(gen_lines) - len(com_lines))
        print(
            f"error: {DST.name} has drifted from the generator ({diff} differing "
            "lines; generated is authoritative). Never hand-edit the PG file — "
            "run: python3 scripts/generate-pg-migration.py\n"
            "If the drift is in a trigger, port the plpgsql in TRIGGER_MAP first.",
            file=sys.stderr,
        )
        return 1

    DST.write_text(body, encoding="utf-8", newline="")
    print(f"wrote {DST} ({n_tables} tables, {n_indexes} indexes, {n_seeds} seed inserts)")
    if skipped:
        print("skipped PG-incompatible indexes (SQLite-only): " + ", ".join(sorted(skipped)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
